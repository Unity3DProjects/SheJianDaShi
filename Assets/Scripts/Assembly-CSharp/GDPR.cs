public static class GDPR
{
	public enum ConsentType
	{
		PrivacyPolicy = 0,
		TargetedAds = 1
	}

	public enum ConsentState
	{
		Unavailable = 0,
		NotRelevant = 1,
		NotSeen = 2,
		Answered = 3
	}

	public enum FetchConsentResult
	{
		Success = 0,
		AlreadyFetching = 1,
		NoUserId = 2,
		NoEndpointUrl = 3,
		NoToken = 4,
		InvalidToken = 5,
		ConnectionError = 6,
		UnknownError = 7
	}

	public enum EndpointType
	{
		Development = 0,
		Production = 1
	}

	public struct ConsentData
	{
		public ConsentType type;

		public ConsentState state;

		public bool shouldAskConsent;

		public bool consentIsGiven;

		public bool readOnly;

		public override string ToString()
		{
			return string.Format("<ConsentData> type: {0}, state: {1}, shouldAskConsent: {2}, ConsentIsGiven: {3}, readOnly: {4}", type.ToString(), state.ToString(), shouldAskConsent, consentIsGiven, readOnly);
		}
	}

	public delegate void ConsentsResponseCallback(FetchConsentResult result, ConsentData[] data);

	private static GDPRInterface implementation;

	public static ConsentsResponseCallback ConsentsResponseListeners;

	static GDPR()
	{
		implementation = new GDPRMobileImplementation();
	}

	public static bool SetupWithCustomToken(string userId, string userToken, string endPointUrl, string country = "")
	{
		return implementation.SetupWithCustomToken(userId, userToken, endPointUrl, country);
	}

	public static bool SetupWithAutoGeneratedToken(string userId, string gameId, string tokenKey, string endPointUrl, string country = "")
	{
		return implementation.SetupWithAutoGeneratedToken(userId, gameId, tokenKey, endPointUrl, country);
	}

	public static void SetConsentStateDefaults(ConsentType type, ConsentState state, bool shouldAskConsent, bool assumedAnswer, bool assumedAnswerWhenReadOnly)
	{
		implementation.SetConsentStateDefaults(type, state, shouldAskConsent, assumedAnswer, assumedAnswerWhenReadOnly);
	}

	public static void FetchCurrentConsents(bool forceImmediateResponse)
	{
		implementation.FetchCurrentConsents(forceImmediateResponse);
	}

	public static bool SetUserAnswer(ConsentType ConsentType, bool answer)
	{
		return implementation.SetUserAnswer(ConsentType, answer);
	}

	public static bool SetKeywordForConsentType(ConsentType type, string keyword)
	{
		return implementation.SetKeywordForConsentType(type, keyword);
	}

	public static void SetFetchTimeout(float timeout)
	{
		implementation.SetFetchTimeout(timeout);
	}

	public static void SetCachedDataValidityDuration(ConsentType type, float days)
	{
		implementation.SetCachedDataValidityDuration(type, days);
	}

	public static void InvalidateCachedData(ConsentType type)
	{
		implementation.InvalidateCachedData(type);
	}

	public static void ForgetUser()
	{
		implementation.ForgetUser();
	}

	public static bool SetExpirationTimeForAutoGeneratedTokens(long expirationTime)
	{
		return implementation.SetExpirationTimeForAutoGeneratedTokens(expirationTime);
	}

	public static void SetDateOfBirthForAutoGeneratedTokens(long dateOfBirthTimestamp)
	{
		implementation.SetDateOfBirthForAutoGeneratedTokens(dateOfBirthTimestamp);
	}
}

using System;
using System.Diagnostics;
using System.Runtime.CompilerServices;
using System.Threading;
using Mit_Goliath_Native.Utils;
using UnityEngine;
using Debug = UnityEngine.Debug;

public class GDPRManager : SingletonMonoBehaviour<GDPRManager>
{
	private static string gameId = "bowmasters";

	private static string tokenKey = "v34zyDxhn4XcJ767k6xz6nVX2ujqJAe9";

	private static string endpointUrl = "https://prod-bowmasters-bacon.miniclippt.com";

	private GDPR.FetchConsentResult lastConsentResult;

	private GDPR.ConsentData lastPrivacyConsentData;

	private GDPR.ConsentData lastTargetedAdsConsentData;

	private bool isShowingPopup;

	public bool IsFetching;

	public bool DataFetched;

	[CompilerGenerated]
	[DebuggerBrowsable(DebuggerBrowsableState.Never)]
	private Action m_OnDataReceived;

	private Managers cachedManagers;

	public bool PrivacyPolicyAccepted;

	private bool isRelevant;

	private bool targetedAdsConsent;

	private Managers CachedManagers
	{
		get
		{
			if (cachedManagers == null)
			{
				cachedManagers = SingletonMonoBehaviour<Managers>.Instance;
			}
			return cachedManagers;
		}
	}

	public bool IsRelevant
	{
		get
		{
			if (!DataFetched)
			{
				FetchDataFromBacon(false);
				return isRelevant;
			}
			return isRelevant;
		}
		set
		{
			isRelevant = value;
		}
	}

	public bool TargetedAdsConsent
	{
		get
		{
			if (!DataFetched)
			{
				FetchDataFromBacon(false);
				return targetedAdsConsent;
			}
			return targetedAdsConsent;
		}
		set
		{
			targetedAdsConsent = value;
			if (MCMoPubManager.Instance.IsMoPubInitialized)
			{
				MCMoPubManager.Instance.SetTargetedAdsConsent(targetedAdsConsent);
			}
			MiniclipUtils.SetGDPRConsentForThirdPartyProviders(IsRelevant, value);
		}
	}

	public event Action OnDataReceived
	{
		add
		{
			Action action = this.m_OnDataReceived;
			Action action2;
			do
			{
				action2 = action;
				action = Interlocked.CompareExchange(ref this.m_OnDataReceived, (Action)Delegate.Combine(action2, value), action);
			}
			while (action != action2);
		}
		remove
		{
			Action action = this.m_OnDataReceived;
			Action action2;
			do
			{
				action2 = action;
				action = Interlocked.CompareExchange(ref this.m_OnDataReceived, (Action)Delegate.Remove(action2, value), action);
			}
			while (action != action2);
		}
	}

	private void OnEnable()
	{
		Debug.Log("UserID for GDPR: " + MiniclipUtils.GetAdvertisingId());
		GDPR.ConsentsResponseListeners = (GDPR.ConsentsResponseCallback)Delegate.Combine(GDPR.ConsentsResponseListeners, new GDPR.ConsentsResponseCallback(ConsentResponse));
		MCMoPubManager.OnSdkInitializedEvent += MCMoPubManager_onSdkInitalizedEvent;
	}

	public void Initialize()
	{
		FetchDataFromBacon(false);
	}

	private void OnDisable()
	{
		GDPR.ConsentsResponseListeners = (GDPR.ConsentsResponseCallback)Delegate.Remove(GDPR.ConsentsResponseListeners, new GDPR.ConsentsResponseCallback(ConsentResponse));
		MCMoPubManager.OnSdkInitializedEvent -= MCMoPubManager_onSdkInitalizedEvent;
	}

	private void FetchDataFromBacon(bool forceImmediateResponse)
	{
		if (!IsFetching)
		{
			IsFetching = true;
			GDPR.SetupWithAutoGeneratedToken(MiniclipUtils.GetAdvertisingId(), gameId, tokenKey, endpointUrl, string.Empty);
			GDPR.FetchCurrentConsents(forceImmediateResponse);
		}
	}

	private void MCMoPubManager_onSdkInitalizedEvent()
	{
		if (DataFetched)
		{
			if (lastTargetedAdsConsentData.state == GDPR.ConsentState.Answered)
			{
				TargetedAdsConsent = lastTargetedAdsConsentData.consentIsGiven;
			}
		}
		else
		{
			TargetedAdsConsent = false;
		}
		if (MCMoPubManager.Instance.IsMoPubInitialized)
		{
			MCMoPubManager.Instance.SetTargetedAdsConsent(targetedAdsConsent);
		}
	}

	private void ConsentResponse(GDPR.FetchConsentResult result, GDPR.ConsentData[] data)
	{
		MiniclipManager.Instance.AddCallbackToQueue(delegate
		{
			IsFetching = false;
			Debug.Log(string.Concat("Fetch Consent Result: ", result, " data1: ", data[0].ToString(), " data2: ", data[1].ToString()));
			if (result == GDPR.FetchConsentResult.Success)
			{
				DataFetched = true;
				SaveConsentData(data);
				IsRelevant = lastTargetedAdsConsentData.state != GDPR.ConsentState.NotRelevant;
				if (lastTargetedAdsConsentData.state == GDPR.ConsentState.Answered)
				{
					TargetedAdsConsent = lastTargetedAdsConsentData.consentIsGiven;
				}
			}
			this.m_OnDataReceived?.Invoke();
		});
	}

	private void SaveConsentData(GDPR.ConsentData[] data)
	{
		for (int i = 0; i < data.Length; i++)
		{
			GDPR.ConsentData consentData = data[i];
			switch (consentData.type)
			{
			case GDPR.ConsentType.PrivacyPolicy:
				lastPrivacyConsentData = consentData;
				break;
			case GDPR.ConsentType.TargetedAds:
				lastTargetedAdsConsentData = consentData;
				break;
			}
		}
	}

	public void ShowRandomPopup()
	{
		CachedManagers.CachedGUIPopupManager.ShowPopup(PopupType.GiftPopup, true, null, true);
	}

	public GDPRPopup ShowIntroTargetedAdsPopup()
	{
		isShowingPopup = true;
		TargetedAdsIntroPopup targetedAdsIntroPopup = (TargetedAdsIntroPopup)CachedManagers.CachedGUIPopupManager.ShowPopup(PopupType.TargetedAdsPopupIntro, true, null, true, true);
		targetedAdsIntroPopup.OnAgreedClicked += GDPRPopup_OnButtonAgreeClicked;
		targetedAdsIntroPopup.OnRefusedClicked += GDPRPopup_OnButtonRefusedClicked;
		GameGoliath.Instance.TrackPrivacyPolicyConsent(GoliathIds.GDPRStep.IMPRESSION, GoliathIds.GDPRContext.PRIVACY_POLICY_WITH_AD_CONSENT);
		return targetedAdsIntroPopup;
	}

	public GDPRPopup ShowSettingsTargetedAdsPopup()
	{
		isShowingPopup = true;
		TargetedAdsSettingsPopup targetedAdsSettingsPopup = (TargetedAdsSettingsPopup)CachedManagers.CachedGUIPopupManager.ShowPopup(PopupType.TargetedAdsPopupSettings);
		targetedAdsSettingsPopup.OnAgreedClicked += GDPRPopup_OnButtonAgreeClicked;
		targetedAdsSettingsPopup.OnRefusedClicked += GDPRPopup_OnButtonRefusedClicked;
		targetedAdsSettingsPopup.OnCheckPrivacyClicked += GDPRPopup_OnCheckPrivacyClicked;
		GameGoliath.Instance.TrackPrivacyPolicyConsent(GoliathIds.GDPRStep.IMPRESSION, GoliathIds.GDPRContext.SETTINGS_POPUP);
		return targetedAdsSettingsPopup;
	}

	public GDPRPopup ShowPrivacyPolicyPopup()
	{
		isShowingPopup = true;
		PrivacyPolicyPopup privacyPolicyPopup = (PrivacyPolicyPopup)CachedManagers.CachedGUIPopupManager.ShowPopup(PopupType.PrivacyPolicyPopup, true, null, true, true);
		privacyPolicyPopup.OnAgreedClicked += GDPRPopup_OnButtonAgreeClicked;
		privacyPolicyPopup.OnCheckPrivacyClicked += GDPRPopup_OnCheckPrivacyClicked;
		return privacyPolicyPopup;
	}

	public void ShowPopupIfRequired()
	{
		if (!isShowingPopup)
		{
			if (ShouldAskConsentForPrivacyPolicy())
			{
				ShowPrivacyPolicyPopup();
			}
			else if (ShouldAskConsentForAds())
			{
				ShowIntroTargetedAdsPopup();
			}
		}
	}

	private bool ShouldAskConsentForAds()
	{
		if (!DataFetched)
		{
			return false;
		}
		return lastTargetedAdsConsentData.shouldAskConsent;
	}

	private bool ShouldAskConsentForPrivacyPolicy()
	{
		if (!DataFetched)
		{
			return false;
		}
		return lastPrivacyConsentData.shouldAskConsent;
	}

	public void GDPRPopup_OnButtonAgreeClicked()
	{
		isShowingPopup = false;
	}

	public void GDPRPopup_OnButtonRefusedClicked()
	{
		isShowingPopup = false;
	}

	public void GDPRPopup_OnCheckPrivacyClicked()
	{
		isShowingPopup = false;
	}
}

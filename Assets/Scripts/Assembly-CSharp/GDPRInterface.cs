public interface GDPRInterface
{
	bool SetupWithAutoGeneratedToken(string userId, string gameId, string tokenKey, string endPointUrl, string country = "");

	bool SetupWithCustomToken(string userId, string userToken, string endPointUrl, string country = "");

	void SetConsentStateDefaults(GDPR.ConsentType type, GDPR.ConsentState state, bool shouldAskConsent, bool assumedAnswer, bool assumedAnswerWhenReadOnly);

	void FetchCurrentConsents(bool forceImmediateResponse);

	bool SetUserAnswer(GDPR.ConsentType ConsentType, bool answer);

	bool SetKeywordForConsentType(GDPR.ConsentType type, string keyword);

	void SetFetchTimeout(float timeout);

	void SetCachedDataValidityDuration(GDPR.ConsentType type, float days);

	void InvalidateCachedData(GDPR.ConsentType type);

	void InvalidateAllCachedData();

	void ForgetUser();

	bool SetExpirationTimeForAutoGeneratedTokens(long expirationTime);

	void SetDateOfBirthForAutoGeneratedTokens(long dateOfBirthTimestamp);

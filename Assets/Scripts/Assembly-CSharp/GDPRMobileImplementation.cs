	[MonoPInvokeCallback(typeof(ConsentsResponseCallback))]
	private static void ConsentsResponseNativeCallback(GDPR.FetchConsentResult result, IntPtr marshaledData, int dataLength)
	{
		int num = Marshal.SizeOf(typeof(MarshaledConsentData));
		MarshaledConsentData[] array = new MarshaledConsentData[dataLength];
		GDPR.ConsentData[] array2 = new GDPR.ConsentData[dataLength];
		for (int i = 0; i < dataLength; i++)
		{
			IntPtr ptr = new IntPtr(marshaledData.ToInt64() + num * i);
			array[i] = (MarshaledConsentData)Marshal.PtrToStructure(ptr, typeof(MarshaledConsentData));
			array2[i].type = array[i].type;
			array2[i].state = array[i].state;
			array2[i].shouldAskConsent = Convert.ToBoolean(array[i].shouldAskConsent);
			array2[i].consentIsGiven = Convert.ToBoolean(array[i].consentIsGiven);
			array2[i].readOnly = Convert.ToBoolean(array[i].readOnly);
		}
		if (GDPR.ConsentsResponseListeners != null)
		{
			GDPR.ConsentsResponseListeners(result, array2);
		}
	}

